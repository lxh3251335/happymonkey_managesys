import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const require = createRequire(new URL('../frontend/package.json', import.meta.url))
const { chromium } = require('playwright')
process.chdir(fileURLToPath(new URL('../', import.meta.url)))
// This destructive fixture run must use a separate, disposable backend database.
const base = process.env.TEST_BASE_URL
if (!base || process.env.ALLOW_TEST_FIXTURES !== '1') throw Error('Set TEST_BASE_URL for an isolated test server and ALLOW_TEST_FIXTURES=1')
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) })
const page = await browser.newPage({ viewport: { width: 1600, height: 1120 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
await page.goto(`${base}/login`)
await page.getByLabel('用户名', { exact: true }).fill('admin')
await page.getByLabel('密码', { exact: true }).fill(process.env.TEST_ADMIN_PASSWORD || 'DevAdmin2026!')
await page.getByRole('button', { name: '登录工作空间' }).click()
await page.waitForURL(`${base}/`)
let token = await (await page.request.get(`${base}/api/auth/csrf`)).json()
async function post(path, body) {
  const response = await page.request.post(`${base}/api${path}`, { data: body, headers: { [token.header]: token.token } })
  assert.equal(response.status(), 200, `${path}: ${await response.text()}`)
  const text = await response.text()
  return text ? JSON.parse(text) : undefined
}
const suffix = String(Date.now())
const client = await post('/partners', { name: `验收客户-${suffix}`, kind: 'CUSTOMER' })
const product = await post('/products', { brand: '小象', name: `验收电箱-${suffix}`, specification: '650×850×250', model: 'E2E', unit: '台' })
const project = await post('/projects', { brand: '小象', name: `验收门店-${suffix}`, customerId: client.id, externalId: `YZL-${suffix}` })
await page.goto(`${base}/quotes?project=${project.id}&new=1`)
const editor = page.getByRole('dialog', { name: '创建客户报价' })
await editor.waitFor()
await editor.locator('.editor-table .el-select').click()
await page.getByRole('option', { name: new RegExp(`验收电箱-${suffix}`) }).click()
const spin = editor.getByRole('spinbutton')
await spin.nth(0).fill('2')
await spin.nth(1).fill('1000')
await spin.nth(2).fill('600')
await editor.getByRole('button', { name: '保存报价草稿' }).click()
const detail = page.getByRole('dialog', { name: '报价详情' })
await detail.getByText('¥2,000.00').first().waitFor()
await detail.getByRole('button', { name: '出具报价', exact: true }).click()
await detail.getByText('已出具', { exact: true }).waitFor()
const popupPromise = page.waitForEvent('popup')
await detail.getByRole('button', { name: '生成对客报价单' }).click()
const popup = await popupPromise
await popup.locator('.customer-quote-table tbody tr').waitFor()
assert(!await popup.locator('body').innerText().then(s => s.includes('成本') || s.includes('利润')))
await fs.mkdir('artifacts', { recursive: true })
await popup.screenshot({ path: 'artifacts/customer-quotation.png', fullPage: true, animations: 'disabled' })
await popup.emulateMedia({ media: 'print' })
await popup.pdf({ path: 'artifacts/customer-quotation-check.pdf', format: 'A4', printBackground: true })
await popup.close()
await detail.getByRole('button', { name: '确认订单与应收' }).click()
await page.getByRole('dialog', { name: '确认客户订单' }).getByRole('button', { name: '确认并建立应收' }).click()
await detail.getByText('已确认', { exact: true }).waitFor()
await page.goto(`${base}/cash`)
await page.getByRole('row').filter({ hasText: `验收门店-${suffix}` }).getByRole('button', { name: '登记回款', exact: true }).click()
const cash = page.getByRole('dialog', { name: '登记客户收付款' })
await cash.getByRole('spinbutton').fill('500')
await cash.locator('.el-form-item').filter({ hasText: '凭证 / 银行流水号' }).getByRole('textbox').fill(`TEST-BANK-${suffix}`)
await cash.getByRole('button', { name: '登记流水' }).click()
await cash.waitFor({ state: 'hidden' })
const row = page.getByRole('row').filter({ hasText: `验收门店-${suffix}` })
await row.getByText('¥1,500.00', { exact: true }).waitFor()
